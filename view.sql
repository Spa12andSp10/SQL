CREATE OR REPLACE VIEW `average_score` AS
SELECT s.firstname, s.lastname, sub.name AS subject, AVG(sm.mark) AS avg_marks
FROM students AS s
JOIN subjects AS sub
JOIN student_marks AS sm ON sm.student_id = s.id AND sm.subject_id = sub.id
GROUP BY s.id, sub.id
ORDER BY s.lastname, sub.name;

SELECT * FROM average_score;
--------------
CREATE OR REPLACE VIEW `number_of_scores` AS
SELECT s.lastname, sm.mark, COUNT(sm.mark) AS quantity
FROM students AS s
JOIN student_marks AS sm ON sm.student_id = s.id
GROUP BY s.id, sm.mark
ORDER BY s.lastname, sm.mark;

SELECT * FROM number_of_scores;
--------------
CREATE OR REPLACE VIEW `best_student` AS
SELECT lastname, SUM(avg_marks)
FROM (
    SELECT s.lastname, AVG(sm.mark) AS avg_marks
    FROM student_marks AS sm
    JOIN students AS s ON sm.student_id = s.id
    GROUP BY sm.student_id
) AS students_avg_marks
GROUP BY lastname
ORDER BY SUM(avg_marks) DESC
LIMIT 1;

SELECT * FROM best_student;

CREATE OR REPLACE VIEW `worst_student` AS
SELECT lastname, SUM(avg_marks)
FROM (
    SELECT s.lastname, AVG(sm.mark) AS avg_marks
    FROM student_marks AS sm
    JOIN students AS s ON sm.student_id = s.id
    GROUP BY sm.student_id
) AS students_avg_marks
GROUP BY lastname
ORDER BY SUM(avg_marks)
LIMIT 1;

SELECT * FROM worst_student;
--------------
CREATE OR REPLACE VIEW `easy_subject` AS
SELECT sub.name, AVG(sm.mark)
FROM subjects AS sub
JOIN student_marks AS sm ON sm.subject_id = sub.id
GROUP BY sub.name
ORDER BY AVG(sm.mark) DESC
LIMIT 1;

SELECT * FROM easy_subject;

